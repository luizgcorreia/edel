def clean_latex(text):

    if not text:
        return ""

    text = re.sub(r"\\cite\{.*?\}", "", text)
    text = re.sub(r"\\[a-zA-Z]+\{(.*?)\}", r"\1", text)
    text = re.sub(r"\$.*?\$", "", text)
    text = re.sub(r"\s+", " ", text)

    return text.strip()


def parse_authors_latex(author_text):

    if not author_text:
        return []

    # remove LaTeX commands
    author_text = re.sub(r"\\thanks\{.*?\}", "", author_text)
    author_text = re.sub(r"\\\\.*", "", author_text)
    author_text = re.sub(r"\\[a-zA-Z]+", "", author_text)

    author_text = author_text.replace("\n", " ")

    # split common separators
    parts = re.split(r"\\and| and |,", author_text)

    authors = []

    for p in parts:
        name = p.strip()

        # keep only likely name strings
        if len(name) > 2 and not any(x in name.lower() for x in ["university", "email", "@"]):
            authors.append({"display_name": name})

    return authors

