def sample_abstract_length(mu, sigma):
    return max(200, min(int(np.random.lognormal(mu, sigma)), 4000))

def load_lexicon(lexicon_file=None):
  if lexicon_file:
    with open(lexicon_file, "r") as f:
        return f.read().splitlines()
  else:
    vocab = [
      w for w in top_n_list("en", n=100000)
      if zipf_frequency(w, "en") > 3
    ]

    # basic cleanup
    vocab = [
        w for w in vocab
        if w.isalpha() and len(w) > 2
    ]

    return vocab

def build_pos_lexicon(n=100000, min_zipf=3):

    freq_words = {
        w.lower() for w in top_n_list("en", n=n)
        if zipf_frequency(w, "en") > min_zipf and w.isalpha() and w.islower() and len(w) > 3
    }

    wn_pos = lambda p: {l.name().lower() for s in wn.all_synsets(p) for l in s.lemmas()}

    nouns = freq_words & wn_pos("n")
    verbs = freq_words & wn_pos("v")
    adjs  = freq_words & wn_pos("a")
    advs  = freq_words & wn_pos("r")

    return {
      "NOUN": sorted(nouns),
      "VERB": sorted(verbs),
      "ADJ": sorted(adjs),
      "ADV": sorted(advs)
    }


def generate_random_sentence(avg_length, lexicon, join=True):
  length = np.random.poisson(avg_length)
  words = np.random.choice(lexicon, size=length)
  if join:
    return " ".join(words).capitalize()

  return words

