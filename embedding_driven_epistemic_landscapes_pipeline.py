def add_deltas(
    df,
    method,
):

    px = f"proj_p_{method}_x"
    py = f"proj_p_{method}_y"

    mx = f"proj_m_{method}_x"
    my = f"proj_m_{method}_y"

    fx = f"proj_f_{method}_x"
    fy = f"proj_f_{method}_y"

    ix = f"proj_i_{method}_x"
    iy = f"proj_i_{method}_y"

    df["d_pm_x"] = df[mx] - df[px]
    df["d_pm_y"] = df[my] - df[py]

    df["d_mf_x"] = df[fx] - df[mx]
    df["d_mf_y"] = df[fy] - df[my]

    df["d_fi_x"] = df[ix] - df[fx]
    df["d_fi_y"] = df[iy] - df[fy]

    return df

def assign_grid(
    df,
    method,
    grid_size,
):

    px = f"proj_p_{method}_x"
    py = f"proj_p_{method}_y"

    xmin, xmax = df[px].min(), df[px].max()
    ymin, ymax = df[py].min(), df[py].max()

    dx = (xmax - xmin) / grid_size
    dy = (ymax - ymin) / grid_size

    df["cell_ix"] = np.floor(
        (df[px] - xmin) / dx
    ).astype(int)

    df["cell_iy"] = np.floor(
        (df[py] - ymin) / dy
    ).astype(int)

    df["cell_ix"] = df["cell_ix"].clip(0, grid_size - 1)
    df["cell_iy"] = df["cell_iy"].clip(0, grid_size - 1)

    df["cell_id"] = (
        df["cell_ix"].astype(str)
        + "_"
        + df["cell_iy"].astype(str)
    )

    df["_xmin"] = xmin
    df["_ymin"] = ymin
    df["_dx"] = dx
    df["_dy"] = dy

    return df

def compute_vector_field(
    df,
    min_count,
):

    g = df.groupby("cell_id")

    field = g.agg(

        cell_ix=("cell_ix", "first"),
        cell_iy=("cell_iy", "first"),

        xmin=("_xmin", "first"),
        ymin=("_ymin", "first"),
        dx=("_dx", "first"),
        dy=("_dy", "first"),

        vf_pm_x=("d_pm_x", "mean"),
        vf_pm_y=("d_pm_y", "mean"),

        vf_mf_x=("d_mf_x", "mean"),
        vf_mf_y=("d_mf_y", "mean"),

        vf_fi_x=("d_fi_x", "mean"),
        vf_fi_y=("d_fi_y", "mean"),

        count=("cell_id", "size"),

    ).reset_index()

    field = field[field["count"] >= min_count]

    # compute cell center

    field["cell_px"] = (
        field["xmin"]
        + (field["cell_ix"] + 0.5) * field["dx"]
    )

    field["cell_py"] = (
        field["ymin"]
        + (field["cell_iy"] + 0.5) * field["dy"]
    )

    return field


