def unique_preserve_order(items):
    seen = set()
    result = []
    for x in items:
        if x not in seen:
            seen.add(x)
            result.append(x)
    return result

# Clean import tokens after parsing
def clean_imports(imports):

    imports = unique_preserve_order(imports)

    cleaned = []

    for x in imports:

        x_clean = x.lower()

        if "/" in x or "." in x:
            continue

        if x_clean in BAD_CONTEXT_TOKENS:
            continue

        cleaned.append(x)

    return cleaned

# Clean lemma tokens after parsing
def clean_lemmas(lemmas):

    BAD_LEMMA_TOKENS = {
        "assumes",
        "shows",
        "fixes"
    }

    lemmas = unique_preserve_order(lemmas)

    cleaned = []

    for l in lemmas:

        l_clean = l.lower()

        if len(l_clean) < 4:
            continue

        if l_clean in BAD_LEMMA_TOKENS:
            continue

        if l_clean.startswith(("aux", "tmp", "helper", "self", "example", "lem", "lemma", "theorem")):
            continue

        if re.match(r"(lem|lemma|theorem)\d+", l_clean):
            continue

        cleaned.append(l)

    return cleaned

# Clean definition tokens after parsing
def clean_definitions(defs):
    defs = unique_preserve_order(defs)
    return [d for d in defs if len(d) > 2]

# Clean theory tokens after parsing
def clean_theories(theories):

    theories = unique_preserve_order(theories)

    cleaned = []

    for t in theories:

        if not isinstance(t, str):
            continue

        t_clean = t.lower()

        if "." in t:
            continue

        if t_clean in BAD_CONTEXT_TOKENS:
            continue

        cleaned.append(t)

    return cleaned

# Sample k items with stratification (25% start, 50% middle, 25% end)
def stratified_sample(items, k):

    n = len(items)

    if n <= k:
        return items

    start_n = k // 4
    end_n = k // 4
    mid_n = k - start_n - end_n

    start = items[:start_n]
    end = items[-end_n:]

    step = n / mid_n

    middle = [items[math.floor(i * step)] for i in range(mid_n)]

    return start + middle + end

# Select semantic entities for each epistemic aspect
def select_entities(row):

    definitions = stratified_sample(row["definitions"], 15)
    lemmas = stratified_sample(row["lemmas"], 20)

    imports = row["imports"]
    theories = row["theories"]

    return definitions, lemmas, imports, theories

def normalize_token(token):
    """
    Normalize Isabelle identifiers for embedding usage.
    """

    if not isinstance(token, str):
        return None

    token = token.strip()

    # Replace underscores and hifens with spaces
    token = token.replace("_", " ")
    token = token.replace("-", " ")

    # Split CamelCase
    token = re.sub(r'([a-z])([A-Z])', r'\1 \2', token)

    # Lowercase
    token = token.lower()

    # Remove extra spaces
    token = re.sub(r'\s+', ' ', token)

    return token.strip()

def normalize_token_list(tokens):
    if not tokens:
        return []

    normalized = []
    seen = set()

    for t in tokens:
        t = normalize_token(t)

        if t and len(t) > 2 and t not in seen:
            normalized.append(t)
            seen.add(t)

    return normalized

# Build segment text
def build_segment_text(label, tokens, label2=None, tokens2=None):

    if not tokens and not tokens2:
      return ""

    blocks = []

    if tokens:
        block = f"{label}:\n" + "\n".join(tokens)
        blocks.append(block)

    if tokens2:
        if label2:
            block = f"{label2}:\n" + "\n".join(tokens2)
        else:
            block = "\n".join(tokens2)
        blocks.append(block)

    return "\n".join(blocks)

# Add prefilled epistemic aspect to df
def add_prefilled_segments(df):

    problems = []
    methods = []
    findings = []
    interpretations = []

    for _, row in df.iterrows():

        defs, lems, imps, thys = select_entities(row)

        defs = normalize_token_list(defs)
        lems = normalize_token_list(lems)
        imps = normalize_token_list(imps)
        thys = normalize_token_list(thys)

        method_text = build_segment_text("definitions", defs)

        finding_text = build_segment_text("key lemmas", lems)

        interpretation_text = build_segment_text(
            "imports", imps,
            "theories", thys
        )

        problems.append("")
        methods.append(method_text)
        findings.append(finding_text)
        interpretations.append(interpretation_text)

    df["problem"] = problems
    df["method"] = methods
    df["finding"] = findings
    df["interpretation"] = interpretations

    return df

