def get_work_count(topic_ids, config):

  regions = config["provider"]["region"]

  # Initialize list for summary
  summary_data = []

  # Iterate over each topic
  for topic_name, topic_id in topic_ids.items():
      # Filter string for global count (with abstract, without paratexts)
      global_filter = f"topics.id:{topic_id},has_abstract:true,is_paratext:false"
      global_data = openalex_request(global_filter, per_page=1)
      total_global = global_data.get('meta', {}).get('count', 0)

      time.sleep(1)  # Add a delay of 1 second between requests

      # Count for region
      total_region = 0
      for country_code in regions:
          country_filter = f"topics.id:{topic_id},institutions.country_code:{country_code},has_abstract:true,is_paratext:false"
          region_data = openalex_request(country_filter, per_page=1)
          count = region_data.get('meta', {}).get('count', 0)
          total_region += count

          time.sleep(0.1)  # Add a delay of 1 second between requests

      # Append to summary
      summary_data.append({
          "Topic": topic_name,
          "Total Works (Global)": total_global,
          "Works in region": total_region,
          "Region %": round(100 * total_region / total_global, 2) if total_global > 0 else 0
      })

  # Create DataFrame
  summary_df = pd.DataFrame(summary_data)

  return summary_df

