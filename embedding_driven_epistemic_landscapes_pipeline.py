def load_embeddings_efficiently(df_series, num_rows, emb_dim, dtype=np.float32):
    """
    Loads a pandas Series of JSON string embeddings into a NumPy array efficiently.

    Args:
        df_series (pd.Series): The pandas Series containing JSON strings of embeddings.
        num_rows (int): The number of rows (and embeddings).
        emb_dim (int): The dimensionality of each embedding.
        dtype (np.dtype): The NumPy data type for the array (e.g., np.float32).

    Returns:
        np.ndarray: A NumPy array containing the embeddings.
    """
    # Pre-allocate NumPy array
    embeddings_np = np.empty((num_rows, emb_dim), dtype=dtype)

    print(f"Processing {len(df_series)} rows for column '{df_series.name}'...")

    for i, json_string in enumerate(df_series):
        if pd.notna(json_string): # Check for NaN, None, etc.
            try:
                parsed_list = json.loads(json_string)
                if isinstance(parsed_list, list) and len(parsed_list) == emb_dim:
                    embeddings_np[i, :] = parsed_list
                else:
                    if isinstance(parsed_list, list):
                        print(f"Warning: Row {i} in '{df_series.name}' has embedding length {len(parsed_list)}, expected {emb_dim}. Filling with zeros.")
                    else:
                        print(f"Warning: Row {i} in '{df_series.name}' did not parse into a list (got {type(parsed_list)}). Filling with zeros.")
                    embeddings_np[i, :] = 0.0  # Fill with zeros or handle as an error
            except json.JSONDecodeError:
                print(f"Warning: Row {i} in '{df_series.name}' contains invalid JSON. Filling with zeros.")
                embeddings_np[i, :] = 0.0
            except Exception as e:
                print(f"Warning: Row {i} in '{df_series.name}' encountered an error during parsing/assignment: {e}. Filling with zeros.")
                embeddings_np[i, :] = 0.0
        else:
            # Handle missing JSON string (NaN)
            # print(f"Info: Row {i} in '{df_series.name}' is NaN. Filling with zeros.") # Optional: for verbose logging
            embeddings_np[i, :] = 0.0  # Fill with zeros

    return embeddings_np

def load_embeddings(df):
  # === 1. Load multi-dimensional embeddings efficiently ===
  num_rows = len(df)
  loaded_embeddings = {}
