def prepare_matrix(X):
    X = X - np.mean(X, axis=0)
    X = X / np.linalg.norm(X, axis=1, keepdims=True)
    return X

def make_reducer(
    method,
    n_components=2,
    random_state=0
):
    if method == "umap":
        reducer = umap.UMAP(
            n_components=n_components,
            n_neighbors=15,
            min_dist=0.1,
            metric="cosine",
            random_state=random_state,
        )
    elif method == "pca":
        reducer = PCA(
            n_components=n_components,
            random_state=random_state,
        )
    elif method == "isomap":
        reducer = Isomap(
            n_components=n_components,
            n_neighbors=15,
        )
    elif method == "diffusion":
        k = pydiffmap.kernel.Kernel(epsilon=1, metric='cosine')
        reducer = pydiffmap.diffusion_map.DiffusionMap(
            kernel_object=k,
            alpha=0.5,
            n_evecs=n_components,
            oos='nystroem'
        )
    else:
        raise ValueError(f"Unknown DR method: {method}")
    return reducer

def project_problem_space(
    loaded_embeddings,
    method="umap",
    n_components=2,
    random_state=0,
):
    emb_p = loaded_embeddings["emb_p"]
    X = prepare_matrix(emb_p)
    reducer = make_reducer(
        method=method,
        n_components=n_components,
        random_state=random_state
    )
    # For pydiffmap, we pass X here to the fit_transform method
    coords = reducer.fit_transform(X)
    return coords, reducer

def add_problem_projection_to_df (
    df,
    loaded_embeddings,
    method="umap",
):
    coords, reducer = project_problem_space(
        loaded_embeddings,
        method=method,
    )
    df[f"proj_p_{method}_x"] = coords[:, 0]
    df[f"proj_p_{method}_y"] = coords[:, 1]
    print("Projection done:", coords.shape)
    return df, reducer

def add_full_projection_to_df(
    df,
    loaded_embeddings,
    reducer,
    method
):
    emb_m = loaded_embeddings["emb_m"]
    emb_f = loaded_embeddings["emb_f"]
    emb_i = loaded_embeddings["emb_i"]
    Xm = prepare_matrix(emb_m)
    Xf = prepare_matrix(emb_f)
    Xi = prepare_matrix(emb_i)
    M2 = reducer.transform(Xm)
    F2 = reducer.transform(Xf)
    I2 = reducer.transform(Xi)
    df[f"proj_m_{method}_x"] = M2[:, 0]
    df[f"proj_m_{method}_y"] = M2[:, 1]
    df[f"proj_f_{method}_x"] = F2[:, 0]
    df[f"proj_f_{method}_y"] = F2[:, 1]
    df[f"proj_i_{method}_x"] = I2[:, 0]
    df[f"proj_i_{method}_y"] = I2[:, 1]
    return df

