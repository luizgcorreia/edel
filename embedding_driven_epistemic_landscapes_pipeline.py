# ------------------------------------------------

def parse_root_tex(path):

    title = None
    authors = []
    abstract = None

    if not path.exists():
        return title, authors, abstract

    text = path.read_text(errors="ignore")

    t = re.search(r"\\title\{(.+?)\}", text, re.S)
    if t:
        title = clean_latex(t.group(1))

    a = re.search(r"\\author\{(.+?)\}", text, re.S)
    if a:
        authors = parse_authors_latex(a.group(1))

    ab = re.search(r"\\begin\{abstract\}(.+?)\\end\{abstract\}", text, re.S)
    if ab:
        abstract = clean_latex(ab.group(1))

    return title, authors, abstract


