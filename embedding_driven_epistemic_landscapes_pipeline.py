def compute_transition_features(loaded_embeddings):

    d_pm = loaded_embeddings["d_pm"]
    d_mf = loaded_embeddings["d_mf"]
    d_fi = loaded_embeddings["d_fi"]

    pm_n = normalize(d_pm)
    mf_n = normalize(d_mf)
    fi_n = normalize(d_fi)

    def cos(a, b):
        return np.sum(a * b, axis=1)

    features = np.column_stack([
        cos(pm_n, mf_n),
        cos(pm_n, fi_n),
        cos(mf_n, fi_n),
        np.linalg.norm(d_pm, axis=1),
        np.linalg.norm(d_mf, axis=1),
        np.linalg.norm(d_fi, axis=1),
    ])

    return features

