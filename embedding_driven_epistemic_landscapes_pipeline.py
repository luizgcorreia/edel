# === Function to extract all country codes from authorships ===
def extract_country_codes(authorships):
    countries = set()
    for author in authorships:
        institutions = author.get('institutions', [])
        for inst in institutions:
            country = inst.get('country_code')
            if country:
                countries.add(country)
    return list(countries)

# Converts OpenAlex inverted abstract into text
def inverted_index_to_text(inv_idx):
    if not inv_idx:
        return ''
    max_pos = max(pos for positions in inv_idx.values() for pos in positions)
    words = [''] * (max_pos + 1)
    for word, positions in inv_idx.items():
        for pos in positions:
            words[pos] = word
    return ' '.join(words)

# We will filter out entries from the main DataFrame (`df`) where the `abstract_text` contains specific keywords identified (e.g., 'ADVERTISEMENT', 'RETURN TO ISSUE').
def filter_keywords(df, keywords):

  print(f"Shape of DataFrame before filtering non-research works: {df.shape}")

  # Create a condition to identify rows containing any of the keywords in abstract_text
  # Using .str.contains with case=False and na=False for robustness
  condition_non_research = df['abstract_text'].astype(str).str.contains(
      '|'.join(keywords), case=False, na=False
  )

  # Count how many entries will be removed
  num_removed = condition_non_research.sum()
  print(f"Number of non-research works to be removed: {num_removed}")

  # Filter out these non-research works
  df_cleaned_final = df[~condition_non_research].copy()

  print(f"Shape of DataFrame after filtering non-research works: {df_cleaned_final.shape}")

  # Update the main DataFrame
  df = df_cleaned_final

  return df


