def extract_afp_archive(archive_path, extract_parent=None):
    """
    Extract afp-current.tar.gz and return the root directory
    (e.g. afp-2026-02-09).
    """

    archive_path = Path(archive_path)

    if extract_parent is None:
        extract_parent = archive_path.parent

    extract_parent = Path(extract_parent)

    # Inspect archive to determine root folder
    with tarfile.open(archive_path, "r:gz") as tar:
        top_level = {
            member.name.split("/")[0]
            for member in tar.getmembers()
            if member.name and "/" in member.name
        }

    if len(top_level) != 1:
        raise RuntimeError(
            f"Unexpected archive structure: {top_level}"
        )

    root_dir_name = list(top_level)[0]
    root_dir = extract_parent / root_dir_name

    # Extract only if needed
    if not root_dir.exists():
        print(f"Extracting {archive_path} ...")
        with tarfile.open(archive_path, "r:gz") as tar:
            tar.extractall(extract_parent, filter="data")
    else:
        print(f"Archive already extracted: {root_dir}")

    return root_dir

