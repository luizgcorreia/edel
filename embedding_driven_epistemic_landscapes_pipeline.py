def compute_segmentation_metrics(df):

    aspect_columns = ['problem', 'method', 'finding', 'interpretation']

    results = {}

    # ------------------------
    # duplication
    # ------------------------

    for i, col1 in enumerate(aspect_columns):
        for j, col2 in enumerate(aspect_columns):
            if i < j:

                val = (df[col1] == df[col2]).mean()

                results[f"dup_{col1}_{col2}"] = val

    # ------------------------
    # mean segment length
    # ------------------------

    for col in aspect_columns:

        results[f"len_{col}"] = (
            df[col].str.split().str.len().mean()
        )

    # ------------------------
    # total length ratio
    # ------------------------

    df2 = df.copy()

    df2['problem_len'] = df2['problem'].str.split().str.len()
    df2['method_len'] = df2['method'].str.split().str.len()
    df2['finding_len'] = df2['finding'].str.split().str.len()
    df2['interpretation_len'] = df2['interpretation'].str.split().str.len()

    df2['segmented_total_len'] = (
        df2['problem_len'] +
        df2['method_len'] +
        df2['finding_len'] +
        df2['interpretation_len']
    )

    df2['abstract_len'] = df2['abstract_text'].str.split().str.len()

    ratio = (
        df2['segmented_total_len'] /
        df2['abstract_len']
    )

    results["seg_ratio_mean"] = ratio.mean()
    results["seg_ratio_std"] = ratio.std()

    results["abstract_len_mean"] = df2["abstract_len"].mean()
    results["seg_total_mean"] = df2["segmented_total_len"].mean()

    return results

def normalize(x):
    return x / np.linalg.norm(x, axis=1, keepdims=True)

def prepare_embeddings(loaded_embeddings):

    for name in loaded_embeddings:

        emb = loaded_embeddings[name]

        emb = emb - np.mean(emb, axis=0)
        emb = normalize(emb)

        loaded_embeddings[name] = emb

    return loaded_embeddings

def compute_embedding_metrics(emb_p, emb_m, emb_f, emb_i):

    N = emb_p.shape[0]

    def mean_cos(A, B):
        return np.mean(
            cosine_similarity(A, B)
        )

    results = {}

    # intra

    results["sim_pm"] = np.mean(
        [cosine_similarity(emb_p[i:i+1], emb_m[i:i+1])[0,0] for i in range(N)]
    )

    results["sim_pf"] = np.mean(
        [cosine_similarity(emb_p[i:i+1], emb_f[i:i+1])[0,0] for i in range(N)]
    )

    results["sim_pi"] = np.mean(
        [cosine_similarity(emb_p[i:i+1], emb_i[i:i+1])[0,0] for i in range(N)]
    )

    results["sim_mf"] = np.mean(
        [cosine_similarity(emb_m[i:i+1], emb_f[i:i+1])[0,0] for i in range(N)]
    )

    results["sim_mi"] = np.mean(
        [cosine_similarity(emb_m[i:i+1], emb_i[i:i+1])[0,0] for i in range(N)]
    )

    results["sim_fi"] = np.mean(
        [cosine_similarity(emb_f[i:i+1], emb_i[i:i+1])[0,0] for i in range(N)]
    )

    # separability

    aspects = {
        "p": emb_p,
        "m": emb_m,
        "f": emb_f,
        "i": emb_i,
    }

    for a_name, A in aspects.items():
        for b_name, B in aspects.items():

            results[f"sep_{a_name}_{b_name}"] = cosine_similarity(A, B).mean()

    # density

    for name, mat in aspects.items():

        sim = cosine_similarity(mat)
        upper = sim[np.triu_indices_from(sim, k=1)]

        results[f"density_{name}_mean"] = upper.mean()
        results[f"density_{name}_std"] = upper.std()

    return results

def compute_operator_metrics(emb_p, emb_m, emb_f, emb_i):

    pm = emb_m - emb_p
    mf = emb_f - emb_m
    fi = emb_i - emb_f

    pm_n = normalize(pm)
    mf_n = normalize(mf)
    fi_n = normalize(fi)

    results = {}

    # norms

    results["norm_pm"] = np.linalg.norm(pm, axis=1).mean()
    results["norm_mf"] = np.linalg.norm(mf, axis=1).mean()
    results["norm_fi"] = np.linalg.norm(fi, axis=1).mean()

    # cosine means

    def cos(a, b):
        return np.sum(a * b, axis=1)

    results["cos_pm_mf"] = cos(pm_n, mf_n).mean()
    results["cos_pm_fi"] = cos(pm_n, fi_n).mean()
    results["cos_mf_fi"] = cos(mf_n, fi_n).mean()

    return results, pm, mf, fi

def compute_structure_metrics(pm, mf, fi, features):

    results = {}

    X = np.vstack([pm, mf, fi])

    kmeans = KMeans(
        n_clusters=3,
        n_init=20,
        random_state=0
    )

    labels = kmeans.fit_predict(X)

    results["silhouette_transitions"] = silhouette_score(X, labels)

    # cosine feature clustering

    kmeans2 = KMeans(
        n_clusters=3,
        n_init=20,
        random_state=0
    )

    labels2 = kmeans2.fit_predict(features)

    results["silhouette_features"] = silhouette_score(features, labels2)

    return results

def run_dataset_experiment(dataset_name, df_subset, loaded_embeddings):

    results = {"dataset": dataset_name}

    # -------------------------
    # segmentation metrics
    # -------------------------

    seg_metrics = compute_segmentation_metrics(df_subset)

    results.update(seg_metrics)

    # -------------------------
    # embeddings
    # -------------------------

    emb_p = loaded_embeddings["emb_p"]
    emb_m = loaded_embeddings["emb_m"]
    emb_f = loaded_embeddings["emb_f"]
    emb_i = loaded_embeddings["emb_i"]

    emb_metrics = compute_embedding_metrics(
        emb_p, emb_m, emb_f, emb_i
    )

    results.update(emb_metrics)

    # -------------------------
    # operators
    # -------------------------

    op_metrics, pm, mf, fi = compute_operator_metrics(
        emb_p, emb_m, emb_f, emb_i
    )

    results.update(op_metrics)

    # -------------------------
    # features
    # -------------------------

    features = compute_transition_features(loaded_embeddings)

    # -------------------------
    # structure
    # -------------------------

    struct_metrics = compute_structure_metrics(
        pm, mf, fi, features
    )

    results.update(struct_metrics)

    return results, features

